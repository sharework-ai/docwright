import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import { defineDocGenerateTool, defineDocValidateTool } from '../src/tools.ts'
import { loadPacks } from '../src/pack-loader.ts'
import { seedContext } from './support.ts'
import { seedContext } from './support.ts'
import { seedContext } from './support.ts'

const packsRoot = fileURLToPath(new URL('../packs', import.meta.url))
const signal = new AbortController().signal

async function makeDeps(overrides: Record<string, unknown> = {}) {
  const packs = await loadPacks(packsRoot, {})
  const pack = packs.get('cosmic-plan')!
  return {
    packs,
    config: {
      provider: 'deepseek',
      model: 'test-model',
      workspaceRoot: await mkdtemp(join(tmpdir(), 'docwright-stale-')),
      maxIterations: 3,
      promptTokenBudget: 60_000,
      ...overrides,
    } as never,
    ctx: {
      llm: {
        stream: async function* () {
          yield { type: 'block-start', index: 0, blockType: 'text' }
          yield { type: 'text-delta', index: 0, text: JSON.stringify(pack.goldenSample) }
          yield { type: 'block-end', index: 0, block: { type: 'text', text: JSON.stringify(pack.goldenSample) } }
          yield { type: 'finish', reason: 'stop' }
        },
      },
    },
  }
}

async function receiptOf(root: string, name: string): Promise<Record<string, unknown>> {
  return JSON.parse(await readFile(join(root, 'topic-a', 'output', `${name}.receipt.json`), 'utf8')) as Record<string, unknown>
}

describe('pack-version staleness in doc_validate', () => {
  it('reports packVersionStale=false for an artifact generated by the installed pack', async () => {
    const deps = await makeDeps()
    await seedContext(deps)
    await defineDocGenerateTool(deps).execute({ pack: 'cosmic-plan', topic: 'topic-a', materials: ['#!inline\nx'], language: 'zh-CN', upstream: ['context/context.json'], params: { cfpTotal: { value: 70, downFactor: 0.9, upFactor: 1.2 } }, confirm: true, artifactName: 'fresh' } as never, { signal } as never)
    const out = await defineDocValidateTool(deps).execute({ artifactPath: 'topic-a/output/fresh.json', pack: 'cosmic-plan', upstream: ['context/context.json'] } as never, { signal } as never) as { packVersionStale: boolean | null }
    expect(out.packVersionStale).toBe(false)
  })

  it('reports packVersionStale=true when the receipt records another pack version', async () => {
    const deps = await makeDeps()
    const root = (deps.config as { workspaceRoot: string }).workspaceRoot
    await seedContext(deps)
    await defineDocGenerateTool(deps).execute({ pack: 'cosmic-plan', topic: 'topic-a', materials: ['#!inline\nx'], language: 'zh-CN', upstream: ['context/context.json'], params: { cfpTotal: { value: 70, downFactor: 0.9, upFactor: 1.2 } }, confirm: true, artifactName: 'old' } as never, { signal } as never)
    const receipt = await receiptOf(root, 'old')
    await writeFile(join(root, 'topic-a', 'output', 'old.receipt.json'), JSON.stringify({ ...receipt, packVersion: '0.0.1' }), 'utf8')
    const out = await defineDocValidateTool(deps).execute({ artifactPath: 'topic-a/output/old.json', pack: 'cosmic-plan', upstream: ['context/context.json'] } as never, { signal } as never) as { receipt: { isValid: boolean }; packVersionStale: boolean | null }
    expect(out.receipt.isValid).toBe(true) // still green, but ...
    expect(out.packVersionStale).toBe(true) // ... certified by an old pack
  })

  it('counts a receipt without a recorded pack version as stale', async () => {
    const deps = await makeDeps()
    const root = (deps.config as { workspaceRoot: string }).workspaceRoot
    await seedContext(deps)
    await defineDocGenerateTool(deps).execute({ pack: 'cosmic-plan', topic: 'topic-a', materials: ['#!inline\nx'], language: 'zh-CN', upstream: ['context/context.json'], params: { cfpTotal: { value: 70, downFactor: 0.9, upFactor: 1.2 } }, confirm: true, artifactName: 'nv' } as never, { signal } as never)
    const receipt = await receiptOf(root, 'nv')
    delete receipt.packVersion
    await writeFile(join(root, 'topic-a', 'output', 'nv.receipt.json'), JSON.stringify(receipt), 'utf8')
    const out = await defineDocValidateTool(deps).execute({ artifactPath: 'topic-a/output/nv.json', pack: 'cosmic-plan', upstream: ['context/context.json'] } as never, { signal } as never) as { packVersionStale: boolean | null }
    expect(out.packVersionStale).toBe(true)
  })

  it('reports packVersionStale=null when no sidecar receipt exists', async () => {
    const deps = await makeDeps()
    const root = (deps.config as { workspaceRoot: string }).workspaceRoot
    await mkdir(root, { recursive: true })
    const { copyFile } = await import('node:fs/promises')
    await copyFile(join(packsRoot, 'cosmic-plan', 'samples', 'golden.json'), join(root, 'sample.json'))
    const out = await defineDocValidateTool(deps).execute({ artifactPath: 'sample.json', pack: 'cosmic-plan', params: { cfpTotal: { value: 70, downFactor: 0.9, upFactor: 1.2 } }, } as never, { signal } as never) as { packVersionStale: boolean | null }
    expect(out.packVersionStale).toBeNull()
  })
})

/** Minimal pack consuming the given upstream type, loaded from an extra dir under the workspace root. */
async function makeChainDeps(overrides: Record<string, unknown> = {}, consumes = 'cosmic-plan') {
  const root = await mkdtemp(join(tmpdir(), 'docwright-chain-'))
  const dir = join(root, 'chain-pack')
  for (const sub of ['rules', 'prompts', 'templates', 'samples']) await mkdir(join(dir, sub), { recursive: true })
  await writeFile(join(dir, 'manifest.json'), JSON.stringify({ name: 'chain-pack', version: '2', description: 'd', consumes: [consumes], languages: ['zh-CN'] }), 'utf8')
  await writeFile(join(dir, 'schema.json'), '{"type":"object"}', 'utf8')
  await writeFile(join(dir, 'rules', 'zh-CN.json'), '[]', 'utf8')
  await writeFile(join(dir, 'prompts', 'zh-CN.md'), 'T {{materials}} {{upstream}}', 'utf8')
  await writeFile(join(dir, 'templates', 'zh-CN.hbs'), 'ok', 'utf8')
  await writeFile(join(dir, 'samples', 'golden.json'), '{}', 'utf8')
  const packs = await loadPacks(packsRoot, { extra: [root] })
  const cosmic = packs.get('cosmic-plan')!
  return {
    packs,
    config: { provider: 'p', model: 'm', workspaceRoot: root, maxIterations: 2, promptTokenBudget: 60_000, ...overrides } as never,
    ctx: {
      llm: {
        stream: async function* () {
          yield { type: 'block-start', index: 0, blockType: 'text' }
          yield { type: 'text-delta', index: 0, text: JSON.stringify(cosmic.goldenSample) }
          yield { type: 'block-end', index: 0, block: { type: 'text', text: JSON.stringify(cosmic.goldenSample) } }
          yield { type: 'finish', reason: 'stop' }
        },
      },
    },
    root,
  }
}

describe('upstream pack-version policy in chained generation', () => {
  it('strict (default) rejects an upstream whose receipt records another pack version', async () => {
    const deps = await makeChainDeps()
    await seedContext(deps)
    await defineDocGenerateTool(deps).execute({ pack: 'cosmic-plan', topic: 'topic-a', materials: ['#!inline\nx'], language: 'zh-CN', upstream: ['context/context.json'], params: { cfpTotal: { value: 70, downFactor: 0.9, upFactor: 1.2 } }, confirm: true, artifactName: 'up' } as never, { signal } as never)
    const receipt = await receiptOf(deps.root, 'up')
    await writeFile(join(deps.root, 'topic-a', 'output', 'up.receipt.json'), JSON.stringify({ ...receipt, packVersion: '0.0.1' }), 'utf8')
    await expect(defineDocGenerateTool(deps).execute({ pack: 'chain-pack', materials: ['#!inline\nx'], upstream: ['topic-a/output/up.json'] } as never, { signal } as never))
      .rejects.toThrow(/generated by "cosmic-plan" v0\.0\.1 .*upstreamVersionPolicy: "warn"/)
  })

  it('strict rejects a receipt without a recorded pack version', async () => {
    const deps = await makeChainDeps()
    await seedContext(deps)
    await defineDocGenerateTool(deps).execute({ pack: 'cosmic-plan', topic: 'topic-a', materials: ['#!inline\nx'], language: 'zh-CN', upstream: ['context/context.json'], params: { cfpTotal: { value: 70, downFactor: 0.9, upFactor: 1.2 } }, confirm: true, artifactName: 'up' } as never, { signal } as never)
    const receipt = await receiptOf(deps.root, 'up')
    delete receipt.packVersion
    await writeFile(join(deps.root, 'topic-a', 'output', 'up.receipt.json'), JSON.stringify(receipt), 'utf8')
    await expect(defineDocGenerateTool(deps).execute({ pack: 'chain-pack', materials: ['#!inline\nx'], upstream: ['topic-a/output/up.json'] } as never, { signal } as never))
      .rejects.toThrow(/vunknown/)
  })

  it('fails loud when the consumed upstream pack is not installed', async () => {
    const deps = await makeChainDeps({}, 'ghost-pack')
    const { writeFile: w } = await import('node:fs/promises')
    const { artifactHashOf } = await import('../src/receipt.ts')
    const artifact = { x: 1 }
    await w(join(deps.root, 'ghost.json'), JSON.stringify(artifact), 'utf8')
    await w(join(deps.root, 'ghost.receipt.json'), JSON.stringify({ isValid: true, pack: 'ghost-pack', packVersion: '1', artifactHash: artifactHashOf(artifact) }), 'utf8')
    await expect(defineDocGenerateTool(deps).execute({ pack: 'chain-pack', materials: ['#!inline\nx'], upstream: ['ghost.json'] } as never, { signal } as never))
      .rejects.toThrow(/no such pack is installed/)
  })

  it('warn proceeds and surfaces upstreamWarnings on the result', async () => {
    const deps = await makeChainDeps({ upstreamVersionPolicy: 'warn' })
    await seedContext(deps)
    await defineDocGenerateTool(deps).execute({ pack: 'cosmic-plan', topic: 'topic-a', materials: ['#!inline\nx'], language: 'zh-CN', upstream: ['context/context.json'], params: { cfpTotal: { value: 70, downFactor: 0.9, upFactor: 1.2 } }, confirm: true, artifactName: 'up' } as never, { signal } as never)
    const receipt = await receiptOf(deps.root, 'up')
    await writeFile(join(deps.root, 'topic-a', 'output', 'up.receipt.json'), JSON.stringify({ ...receipt, packVersion: '0.0.9' }), 'utf8')
    const out = await defineDocGenerateTool(deps).execute({ pack: 'chain-pack', materials: ['#!inline\nx'], upstream: ['topic-a/output/up.json'] } as never, { signal } as never) as { receipt: { isValid: boolean; upstreamHashes: Array<{ packVersion: string }> }; upstreamWarnings?: readonly string[] }
    expect(out.receipt.isValid).toBe(true)
    expect(out.receipt.upstreamHashes[0]!.packVersion).toBe('0.0.9')
    expect(out.upstreamWarnings?.[0]).toMatch(/v0\.0\.9/)
  })

  it('matching versions pass silently without upstreamWarnings', async () => {
    const deps = await makeChainDeps()
    await seedContext(deps)
    await defineDocGenerateTool(deps).execute({ pack: 'cosmic-plan', topic: 'topic-a', materials: ['#!inline\nx'], language: 'zh-CN', upstream: ['context/context.json'], params: { cfpTotal: { value: 70, downFactor: 0.9, upFactor: 1.2 } }, confirm: true, artifactName: 'up' } as never, { signal } as never)
    const out = await defineDocGenerateTool(deps).execute({ pack: 'chain-pack', materials: ['#!inline\nx'], upstream: ['topic-a/output/up.json'] } as never, { signal } as never) as { receipt: { isValid: boolean }; upstreamWarnings?: readonly string[] }
    expect(out.receipt.isValid).toBe(true)
    expect(out.upstreamWarnings).toBeUndefined()
  })
})
